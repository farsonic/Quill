static char *part24(const u8 *data, size_t n, const char *name)
{
  ZipReader z;
  size_t len;
  u8 *b, *t;
  if (!zip_open(&z, data, n)) return NULL;
  b = zip_read(&z, zip_find(&z, name), &len);
  zip_close(&z);
  if (!b) return NULL;
  if (!(t = (u8 *)realloc(b, len + 1))) { free(b); return NULL; }
  t[len] = 0;
  return (char *)t;
}
static void dump24(Doc *d, const char *name)
{
  const char *dir = getenv("WP24_OUT");
  char path[400];
  size_t n;
  u8 *data;
  FILE *f;
  if (!dir || !(data = docx_save(d, &n))) return;
  snprintf(path, sizeof path, "%s/%s", dir, name);
  if ((f = fopen(path, "wb"))) { fwrite(data, 1, n, f); fclose(f); }
  free(data);
}

/* core.xml, app.xml and custom.xml read, edited, written and read back */
static void properties(void)
{
  char err[200];
  unsigned lost;
  Doc *d = doc_load_file("tests/data/word.docx", &lost, err, sizeof err), *e = NULL;
  size_t n;
  u8 *data;
  if (!d) { ok("properties: word.docx loads", 0); return; }
  ok("properties: core.xml read", !strcmp(d->title, "Quill test document") && !strcmp(info_str(d, IP_DESCRIPTION), "generated by python-docx") &&
     !strcmp(info_str(d, IP_REVISION), "1") && !strcmp(info_str(d, IP_CREATED), "2013-12-23T23:15:00Z"));
  ok("properties: app.xml read", !strcmp(info_str(d, IP_TEMPLATE), "Normal.dotm") && d->info->napp > 10 && keep_find(d, "docProps/app.xml") < 0);
  info_set(d, IP_SUBJECT, "Amiga word processing");
  info_set(d, IP_KEYWORDS, "Quill; Amiga");
  info_set(d, IP_COMPANY, "Hyperion & Co <test>");
  info_set(d, IP_MANAGER, "M\xC3\xBCller");
  info_set(d, IP_CATEGORY, "Tests");
  info_cust_set(d, "Client", CP_TEXT, "Acme");
  info_cust_set(d, "Pages planned", CP_NUMBER, "42");
  info_cust_set(d, "Ratio", CP_NUMBER, "1.5");
  info_cust_set(d, "Due", CP_DATE, "2026-11-01T00:00:00Z");
  info_cust_set(d, "Checked", CP_BOOL, "1");
  dump24(d, "props.docx");
  data = docx_save(d, &n);
  {
    char *core = data ? part24(data, n, "docProps/core.xml") : NULL, *app = data ? part24(data, n, "docProps/app.xml") : NULL,
         *cust = data ? part24(data, n, "docProps/custom.xml") : NULL, *rels = data ? part24(data, n, "_rels/.rels") : NULL,
         *ct = data ? part24(data, n, "[Content_Types].xml") : NULL;
    ok("properties: core.xml written", core && strstr(core, "<dc:subject>Amiga word processing</dc:subject>") && strstr(core, "<cp:keywords>Quill; Amiga</cp:keywords>") &&
       strstr(core, "<dcterms:created xsi:type=\"dcterms:W3CDTF\">2013-12-23T23:15:00Z</dcterms:created>") && strstr(core, "<cp:category>Tests</cp:category>"));
    ok("properties: app.xml written, the rest kept", app && strstr(app, "<Company>Hyperion &amp; Co &lt;test&gt;</Company>") && strstr(app, "<Manager>M\xC3\xBCller</Manager>") &&
       strstr(app, "<HeadingPairs>") && strstr(app, "<Application>Quill</Application>") && strstr(app, "<Template>Normal.dotm</Template>"));
    ok("properties: custom.xml written", cust && strstr(cust, "name=\"Client\"><vt:lpwstr>Acme</vt:lpwstr>") && strstr(cust, "<vt:i4>42</vt:i4>") &&
       strstr(cust, "<vt:r8>1.5</vt:r8>") && strstr(cust, "<vt:filetime>2026-11-01T00:00:00Z</vt:filetime>") && strstr(cust, "<vt:bool>true</vt:bool>"));
    ok("properties: their relationships and types", rels && strstr(rels, "Target=\"docProps/app.xml\"") && strstr(rels, "Target=\"docProps/custom.xml\"") &&
       ct && strstr(ct, "/docProps/custom.xml") && strstr(ct, "custom-properties+xml"));
    free(core); free(app); free(cust); free(rels); free(ct);
  }
  e = data ? docx_load(data, n, &lost, err, sizeof err) : NULL;
  ok("properties: read back", e && !strcmp(info_str(e, IP_SUBJECT), "Amiga word processing") && !strcmp(info_str(e, IP_COMPANY), "Hyperion & Co <test>") &&
     !strcmp(info_str(e, IP_MANAGER), "M\xC3\xBCller") && e->info->ncust == 5 && info_cust_find(e, "Due") == 3 && e->info->cust[3].type == CP_DATE &&
     e->info->cust[4].type == CP_BOOL && !strcmp(e->info->cust[4].value, "1") && e->info->cust[1].type == CP_NUMBER && !strcmp(e->info->cust[1].value, "42"));
  free(data); doc_free(e);
  /* saving from the program: modified now, saved by the user, the revision one up */
  info_set_clock("2026-10-29T12:00:00Z"); info_set_user("Tester");
  data = docx_save(d, &n);
  info_set_clock(""); info_set_user("");
  e = data ? docx_load(data, n, &lost, err, sizeof err) : NULL;
  ok("properties: modified, last saved by, revision", e && !strcmp(info_str(e, IP_MODIFIED), "2026-10-29T12:00:00Z") && !strcmp(info_str(e, IP_LASTBY), "Tester") &&
     !strcmp(info_str(e, IP_REVISION), "2"));
  free(data); doc_free(e);
  /* a custom property of a kind Quill doesn't edit, and a linked one, kept */
  {
    static const char cx[] = "<?xml version=\"1.0\"?><Properties xmlns=\"http://schemas.openxmlformats.org/officeDocument/2006/custom-properties\" "
      "xmlns:vt=\"http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes\"><property fmtid=\"{D5CDD505-2E9C-101B-9397-08002B2CF9AE}\" pid=\"2\" "
      "name=\"List\"><vt:vector size=\"1\" baseType=\"lpstr\"><vt:lpstr>a</vt:lpstr></vt:vector></property><property fmtid=\"{D5CDD505-2E9C-101B-9397-08002B2CF9AE}\" "
      "pid=\"3\" name=\"Linked\" linkTarget=\"bm1\"><vt:lpwstr>x</vt:lpwstr></property></Properties>";
    Doc *c = doc_new();
    char *x;
    info_read_custom(c, cx, sizeof cx - 1);
    x = info_custom_xml(c, &n);
    ok("properties: other kinds and links kept", x && strstr(x, "name=\"List\"><vt:vector size=\"1\" baseType=\"lpstr\"><vt:lpstr>a</vt:lpstr></vt:vector></property>") &&
       strstr(x, "name=\"Linked\" linkTarget=\"bm1\"><vt:lpwstr>x</vt:lpwstr>"));
    free(x);
    info_cust_remove(c, 0);
    ok("properties: one taken out", c->info->ncust == 1 && info_cust_find(c, "Linked") == 0);
    /* a new document: app.xml with its statistics, core.xml created on its first save */
    {
      Pos p = P(0, 0);
      doc_insert(c, &p, "Two words.", 10, NULL);
      info_set_clock("2026-10-29T13:00:00Z");
      data = docx_save(c, &n);
      info_set_clock("");
      x = data ? part24(data, n, "docProps/app.xml") : NULL;
      ok("properties: a new document's statistics", x && strstr(x, "<Words>2</Words>") && strstr(x, "<Characters>9</Characters>") && strstr(x, "<CharactersWithSpaces>10</CharactersWithSpaces>"));
      ok("properties: created set once", !strcmp(info_str(c, IP_CREATED), "2026-10-29T13:00:00Z"));
      free(x); free(data);
    }
    doc_free(c);
  }
  doc_free(d);
}
/* a picture marked decorative: written as Word writes it and read back */
static void decorative(void)
{
  char err[200];
  unsigned lost;
  Doc *d = doc_load_file("tests/data/pictures.docx", &lost, err, sizeof err), *e;
  size_t n;
  u8 *data;
  int k;
  if (!d || !d->nimages) { ok("decorative: pictures.docx loads", 0); doc_free(d); return; }
  for (k = 0; k < d->nimages; k++) d->images[k].decorative = (u8)(k == 0);
  data = docx_save(d, &n);
  {
    char *x = data ? part24(data, n, "word/document.xml") : NULL;
    ok("decorative: Word's mark in wp:docPr", x && strstr(x, "<adec:decorative xmlns:adec=\"http://schemas.microsoft.com/office/drawing/2017/decorative\" val=\"1\"/></a:ext></a:extLst></wp:docPr>"));
    free(x);
  }
  e = data ? docx_load(data, n, &lost, err, sizeof err) : NULL;
  ok("decorative: read back", e && e->nimages == d->nimages && e->images[0].decorative && (e->nimages < 2 || !e->images[1].decorative));
  free(data); doc_free(e); doc_free(d);
}
/* Inspect Document: found, then removed */
static void inspect(void)
{
  Doc *d = doc_new();
  Pos p = P(0, 0), a, b;
  InspectReport r;
  CharFmt f;
  int st, rid;
  if (!d) return;
  st = doc_style(d, "Normal");
  doc_insert(d, &p, "Some text to comment on.", 24, NULL);
  doc_comment(d, P(0, 0), P(0, 4), "A remark", "Ann Author", "AA", "2026-10-29T10:00:00Z");
  rid = doc_add_rev(d, "Bob Reviewer", "2026-10-29T10:00:00Z");
  f = d->p[0]->r[d->p[0]->nr - 1].f; f.rev = REV_INS; f.rid = (u16)rid;
  p = doc_end_pos(d);
  doc_insert(d, &p, " Added.", 7, &f);
  story_set_text(d, &d->hdr[HF_DEFAULT], "Confidential", st < 0 ? 0 : st, AL_LEFT);
  strcpy(d->author, "Ann Author");
  info_set(d, IP_COMPANY, "Acme");
  info_cust_set(d, "Client", CP_TEXT, "Someone");
  keep_add(d, "customXml/item1.xml", "application/xml", "word/document.xml", "http://schemas.openxmlformats.org/officeDocument/2006/relationships/customXml", "rId9", "<a/>", 4);
  inspect_doc(d, &r);
  ok("inspect: finds comments, changes, properties, headers, custom XML", r.comments == 1 && r.revisions >= 1 && r.props >= 4 && r.headers == 1 && r.customxml == 1);
  ok("inspect: removes them", inspect_remove(d, INS_COMMENTS | INS_REVISIONS | INS_PROPS | INS_HEADERS | INS_CUSTOMXML) ==
     (INS_COMMENTS | INS_REVISIONS | INS_PROPS | INS_HEADERS | INS_CUSTOMXML));
  inspect_doc(d, &r);
  ok("inspect: nothing left", !r.comments && !r.revisions && !r.props && !r.headers && !r.customxml && !strcmp(d->comments[0].author, "Author") &&
     !strcmp(d->revs[rid].author, "Author") && !d->author[0] && text_is(d, "Some text to comment on. Added."));
  a = P(0, 0); b = a;
  (void)b;
  doc_free(d);
}
/* the accessibility checker's rules */
static void accessibility(void)
{
  Doc *d = doc_new();
  Pos p = P(0, 0);
  AccIssue is[40];
  Image sh;
  int n, k, h1 = -1, h3 = -1, found[AR_N];
  char ref[8];
  CharFmt f;
  if (!d) return;
  ok("accessibility: black on white is 21:1", acc_contrast(0, 0xFFFFFF) == 2100 && acc_contrast(0xFFFFFF, 0xFFFFFF) == 100);
  doc_insert(d, &p, "Heading\nSub-sub heading\nA shape: \n\n\n\nGrey words.\n", 50, NULL);
  for (k = 0; k < d->nstyles; k++) { if (!strcmp(d->styles[k].name, "heading 1")) h1 = k; if (!strcmp(d->styles[k].name, "heading 3")) h3 = k; }
  if (h1 >= 0 && h3 >= 0) {
    ParaFmt pf;
    memset(&pf, 0, sizeof pf);
    pf.style = (u8)h1; doc_para_format(d, 0, 0, PM_STYLE, &pf);
    pf.style = (u8)h3; doc_para_format(d, 1, 1, PM_STYLE, &pf);
  }
  memset(&sh, 0, sizeof sh);
  img_defaults(&sh);
  sh.kind = OBJ_SHAPE; sh.shape = SH_RECT; sh.cx = sh.cy = 720; sh.fill = 0xFF0000;
  k = doc_add_object(d, &sh);
  pic_utf8(ref, k);
  p = P(2, 9); doc_insert(d, &p, ref, 4, NULL);
  f = d->p[6]->r[0].f; f.color = 0xCCCCCC;
  doc_format(d, P(6, 0), P(6, 11), CM_COLOR, &f);
  p = P(7, 0);
  tbl_insert(d, &p, 2, 2, 4000);
  n = acc_check(d, is, 40);
  memset(found, 0, sizeof found);
  for (k = 0; k < n; k++) found[is[k].rule]++;
  ok("accessibility: missing alternative text, an error, first", n && is[0].rule == AR_ALTTEXT && is[0].kind == AK_ERROR && is[0].obj == k - k + d->nimages - 1);
  ok("accessibility: heading level skipped", h1 < 0 || found[AR_HEADINGORDER] == 1);
  ok("accessibility: low contrast", found[AR_CONTRAST] == 1);
  ok("accessibility: empty paragraphs in a row", found[AR_BLANK] == 1);
  ok("accessibility: a table without a header row", found[AR_TABLEHEADER] == 1);
  ok("accessibility: no title", found[AR_TITLE] == 1);
  d->images[d->nimages - 1].decorative = 1;
  strcpy(d->title, "Accessible");
  n = acc_check(d, is, 40);
  memset(found, 0, sizeof found);
  for (k = 0; k < n; k++) found[is[k].rule]++;
  ok("accessibility: decorative needs no alternative text", !found[AR_ALTTEXT] && !found[AR_TITLE]);
  doc_free(d);
}
static void compatibility(void)
{
  char err[200];
  unsigned lost;
  Doc *d = doc_load_file("tests/data/word.docx", &lost, err, sizeof err);
  CompatIssue c[10];
  int n, i, kept = 0;
  if (!d) { ok("compatibility: loads", 0); return; }
  n = compat_check(d, c, 10);
  for (i = 0; i < n; i++) if (strstr(c[i].msg, "doesn't show")) kept = (int)c[i].count;
  ok("compatibility: kept parts reported", kept >= 2);
  doc_free(d);
}
/* recovery copies and versions in a drawer of their own */
static void recovery(void)
{
  char dir[] = "/tmp/quill_wp24_XXXXXX", rd[300], vd[300], path[400], file[400], err[200];
  RecEntry e[8];
  VerEntry v[30];
  Doc *d, *r;
  unsigned lost;
  int a, b, n, i;
  Pos p = P(0, 0);
  size_t len;
  u8 *data;
  FILE *f;
  if (!mkdtemp(dir)) { ok("recovery: a drawer", 0); return; }
  snprintf(rd, sizeof rd, "%s/rec", dir); snprintf(vd, sizeof vd, "%s/ver", dir);
  mkdir(rd, 0700); mkdir(vd, 0700);
  rec_set_dirs(rd, vd);
  d = doc_new();
  doc_insert(d, &p, "Unsaved words.", 14, NULL);
  a = rec_new_id();
  ok("recovery: a copy written", rec_save(a, d, "", "Untitled", "2026-10-29 12:00"));
  b = rec_new_id();
  ok("recovery: a second one", b == a + 1 && rec_save(b, d, "Work:Letter.docx", "Letter.docx", "2026-10-29 12:01"));
  ok("recovery: written again in place", rec_save(a, d, "", "Untitled", "2026-10-29 12:02"));
  n = rec_list(e, 8);
  ok("recovery: listed", n == 2 && e[0].id == b && !strcmp(e[0].path, "Work:Letter.docx") && e[1].id == a && !strcmp(e[1].stamp, "2026-10-29 12:02"));
  rec_file(a, file, sizeof file);
  r = doc_load_file(file, &lost, err, sizeof err);
  ok("recovery: the copy opens", r && text_is(r, "Unsaved words."));
  doc_free(r);
  rec_drop(a); rec_drop(b);
  ok("recovery: dropped", rec_list(e, 8) == 0 && !fopen(file, "rb"));
  /* versions: each save kept, a run of AutoSaves only its last, the newest VER_KEEP */
  snprintf(path, sizeof path, "%s/Doc.docx", dir);
  for (i = 0; i < 4; i++) {
    char w[40];
    sprintf(w, " Save %d.", i);
    p = doc_end_pos(d);
    doc_insert(d, &p, w, (u32)strlen(w), NULL);
    data = docx_save(d, &len);
    if ((f = fopen(path, "wb"))) { fwrite(data, 1, len, f); fclose(f); }
    free(data);
    sprintf(w, "2026-10-29 13:0%d", i);
    ver_add(path, w, i >= 2);
  }
  n = ver_list(path, v, 30);
  ok("versions: saves kept, AutoSaves only the last", n == 3 && v[0].kind == 'a' && !strcmp(v[0].stamp, "2026-10-29 13:03") && v[1].kind == 's' && v[2].n == 1);
  ver_file(path, v[1].n, file, sizeof file);
  r = doc_load_file(file, &lost, err, sizeof err);
  ok("versions: an earlier one opens", r && text_is(r, "Unsaved words. Save 0. Save 1."));
  doc_free(r);
  ok("versions: one deleted", ver_delete(path, v[1].n) && ver_list(path, v, 30) == 2);
  for (i = 0; i < VER_KEEP + 5; i++) ver_add(path, "2026-10-29 14:00", 0);
  n = ver_list(path, v, 30);
  ok("versions: the newest kept", n == VER_KEEP && v[0].n > v[n - 1].n);
  for (i = 0; i < n; i++) { ver_file(path, v[i].n, file, sizeof file); remove(file); }
  {
    char idx[400];
    VerEntry one;
    (void)one;
    ver_file(path, 0, file, sizeof file);
    snprintf(idx, sizeof idx, "%s", file);
    *strrchr(idx, '-') = 0; strcat(idx, ".idx");
    remove(idx);
  }
  snprintf(file, sizeof file, "%s/Recovery.index", rd); remove(file);
  remove(path); rmdir(rd); rmdir(vd); rmdir(dir);
  rec_set_dirs("", "");
  doc_free(d);
}

